using System.Globalization;
using System.Text;
using QuestPDF.Fluent;
using QuestPDF.Helpers;
using QuestPDF.Infrastructure;

namespace ATLAS.Attendance;

/// <summary>
/// Attendance Report Exporter.
/// </summary>
internal static class AttendanceReportExporter
{
    // =========================================================
    // CSV EXPORT
    // =========================================================

    /// <summary>
    /// Write Csv Async.
    /// </summary>
    public static async Task WriteCsvAsync(
        AttendanceReportDto report,
        Stream output,
        CancellationToken cancellationToken = default)
    {
        await using var writer = new StreamWriter(
            output,
            new UTF8Encoding(encoderShouldEmitUTF8Identifier: true),
            bufferSize: 64 * 1024,
            leaveOpen: true);

        // CSV Header
        await writer.WriteLineAsync(
            "Student ID,Student Code,Student Name,Status,Recorded At (UTC)");

        foreach (var row in report.Students)
        {
            cancellationToken.ThrowIfCancellationRequested();

            var recordedAt = row.RecordedAt.HasValue
                ? row.RecordedAt.Value.ToString("O", CultureInfo.InvariantCulture)
                : string.Empty;

            var csvRow = string.Join(",",
                row.StudentId.ToString(CultureInfo.InvariantCulture),
                EscapeCsv(row.StudentCode),
                EscapeCsv(row.StudentName),
                EscapeCsv(row.Status),
                EscapeCsv(recordedAt));

            await writer.WriteLineAsync(csvRow);
        }

        await writer.FlushAsync(cancellationToken);
    }

    /// <summary>
    /// Escape Csv.
    /// </summary>
    private static string EscapeCsv(string? value)
    {
        if (string.IsNullOrEmpty(value))
            return "\"\"";

        // A student controls their own name, and a spreadsheet executes any cell
        // that starts with one of these characters. Prefixing the value with a
        // single quote keeps it as text (LOW-10).
        var neutralised = StartsWithFormula(value)
            ? "'" + value
            : value;

        // CSV requires escaping quotes by doubling them.
        var escaped = neutralised.Replace("\"", "\"\"");

        // Always quote text values to safely handle commas and new lines.
        return $"\"{escaped}\"";
    }

    /// <summary>
    /// Detects a value that a spreadsheet application would treat as a formula.
    /// </summary>
    private static bool StartsWithFormula(string value)
    {
        foreach (var character in value)
        {
            if (char.IsWhiteSpace(character))
                continue;

            return character is '=' or '+' or '-' or '@';
        }

        return false;
    }


    // =========================================================
    // PDF EXPORT
    // =========================================================

    /// <summary>
    /// Write Pdf.
    /// </summary>
    public static void WritePdf(
        AttendanceReportDto report,
        Stream output)
    {
        var document = Document.Create(container =>
        {
            container.Page(page =>
            {
                page.Size(PageSizes.A4);
                page.Margin(30);
                page.DefaultTextStyle(x => x.FontSize(9));

                page.Header()
                    .Element(header => ComposeHeader(header, report));

                page.Content()
                    .Element(content => ComposeContent(content, report));

                page.Footer()
                    .AlignCenter()
                    .Text(text =>
                    {
                        text.Span("Generated by ATLAS | Page ");
                        text.CurrentPageNumber();
                        text.Span(" of ");
                        text.TotalPages();
                    });
            });
        });

        document.GeneratePdf(output);
    }


    /// <summary>
    /// Compose Header.
    /// </summary>
    private static void ComposeHeader(
        IContainer container,
        AttendanceReportDto report)
    {
        container.Column(column =>
        {
            column.Spacing(5);

            column.Item()
                .Text("Attendance Report")
                .Bold()
                .FontSize(18);

            column.Item()
                .Text($"Session ID: {report.SessionId}")
                .FontSize(9);

            column.Item()
                .Text(
                    $"Course Offering: {report.CourseOfferingId} | " +
                    $"Status: {report.Status}")
                .FontSize(10);

            column.Item()
                .LineHorizontal(1);
        });
    }


    /// <summary>
    /// Compose Content.
    /// </summary>
    private static void ComposeContent(
        IContainer container,
        AttendanceReportDto report)
    {
        container.PaddingTop(15).Table(table =>
        {
            table.ColumnsDefinition(columns =>
            {
                columns.ConstantColumn(45);  // Student ID
                columns.ConstantColumn(75);  // Student Code
                columns.RelativeColumn(2);   // Student Name
                columns.ConstantColumn(65);  // Status
                columns.ConstantColumn(110); // Recorded At
            });

            // Table Header
            table.Header(header =>
            {
                header.Cell()
                    .Element(HeaderCellStyle)
                    .Text("ID");

                header.Cell()
                    .Element(HeaderCellStyle)
                    .Text("Code");

                header.Cell()
                    .Element(HeaderCellStyle)
                    .Text("Student Name");

                header.Cell()
                    .Element(HeaderCellStyle)
                    .Text("Status");

                header.Cell()
                    .Element(HeaderCellStyle)
                    .Text("Recorded At UTC");
            });

            // Table Rows
            foreach (var student in report.Students)
            {
                table.Cell()
                    .Element(BodyCellStyle)
                    .Text(student.StudentId.ToString());

                table.Cell()
                    .Element(BodyCellStyle)
                    .Text(student.StudentCode ?? string.Empty);

                table.Cell()
                    .Element(BodyCellStyle)
                    .Text(student.StudentName ?? string.Empty);

                table.Cell()
                    .Element(BodyCellStyle)
                    .Text(student.Status);

                var recordedAt = student.RecordedAt.HasValue
                    ? student.RecordedAt.Value.ToString(
                        "yyyy-MM-dd HH:mm:ss",
                        CultureInfo.InvariantCulture)
                    : "-";

                table.Cell()
                    .Element(BodyCellStyle)
                    .Text(recordedAt);
            }
        });
    }


    /// <summary>
    /// Header Cell Style.
    /// </summary>
    private static IContainer HeaderCellStyle(IContainer container)
    {
        return container
            .Background(Colors.Grey.Lighten2)
            .Border(1)
            .BorderColor(Colors.Grey.Medium)
            .Padding(5)
            .AlignMiddle()
            .DefaultTextStyle(x => x.Bold());
    }


    /// <summary>
    /// Body Cell Style.
    /// </summary>
    private static IContainer BodyCellStyle(IContainer container)
    {
        return container
            .BorderBottom(1)
            .BorderColor(Colors.Grey.Lighten2)
            .Padding(4)
            .AlignMiddle();
    }
}
